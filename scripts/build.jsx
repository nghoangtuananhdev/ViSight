import { writeFile } from 'node:fs/promises';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { pages } from '../src/screens.jsx';

const titles = {
  "01-tong-quan": "ViSight · Tổng quan",
  "02-tim-kiem": "ViSight · Tìm kiếm",
  "03-chuoi-su-kien": "ViSight · Chuỗi sự kiện",
  "04-chi-tiet-video": "ViSight · Chi tiết video",
  "05-tro-ly-ai": "ViSight · Trợ lý AI",
  "06-nop-dap-an": "ViSight · Nộp đáp án",
};

// Commit the generated pages so GitHub Pages and the Figma importer can read them directly.
for (const [slug, Screen] of Object.entries(pages)) {
  const html = renderToStaticMarkup(
    <html lang="vi">
      <head>
        <meta charSet="utf-8" />
        <meta name="viewport" content="width=1440" />
        <title>{titles[slug]}</title>
        <link rel="stylesheet" href="assets/css/base.css" />
        <link rel="stylesheet" href="assets/css/app.css" />
        <link rel="stylesheet" href="assets/css/motion.css" />
      </head>
      <body data-page={slug}>
        <div id="app"><Screen /></div>
      </body>
    </html>,
  );
  await writeFile(new URL(`../app/${slug}.html`, import.meta.url),
    '<!doctype html>\n<!-- Generated by npm run build from src/screens.jsx. -->\n' + html + '\n',
  );
}
